#!/bin/sh
# Regenerates ../shaders.h from GLSL sources, requires glslc (e.g. from Android NDK's shader-tools)
# Usage: generate.sh [path/to/glslc]
set -e
GLSLC=${1:-glslc}
DIR=$(dirname "$0")
OUT="$DIR/../shaders.h"
{
  echo "// Generated by shaders/generate.sh from shaders/*.{vert,frag}, do not edit"
  echo "#pragma once"
  echo "#include <cstdint>"
  echo "namespace VulkanScope::Shaders"
  echo "{"
  for src in trace.vert trace.frag background.vert background.frag; do
    name=$(echo "$src" | tr '.a-z' '_A-Z')
    echo "  const uint32_t $name[] = {"
    "$GLSLC" -O --target-env=vulkan1.0 -mfmt=num -o - "$DIR/$src"
    echo "  };"
  done
  echo "}  // namespace VulkanScope::Shaders"
} > "$OUT"
