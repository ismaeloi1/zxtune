#!/usr/bin/env python3
"""Generates formats tables of the manual from 'zxtune123 --list-plugins' output (stdin)."""
import re
import sys

KIND = {
    'mod_track': 'Tracker module',
    'mod_stream': 'Register stream',
    'mod_memorydump': 'Memory dump',
    'mod_multi': 'Multichip',
}
DEVICE = {
    'dev_ay38910': 'AY-3-8910/YM2149',
    'dev_turbosound': 'TurboSound',
    'dev_turbofm': 'TurboFM (YM2203)',
    'dev_saa1099': 'SAA1099',
    'dev_beeper': 'Beeper',
    'dev_rp2a0x': 'Ricoh 2A03/2A07',
    'dev_co12294': 'Atari POKEY',
    'dev_spc700': 'SPC700/S-DSP',
    'dev_mos6581': 'MOS6581/8580',
    'dev_lr35902': 'Game Boy',
    'dev_huc6270': 'HuC6280',
    'dev_multi': 'Several chips',
    'dev_dac': 'Digital / PCM',
}
CONTAINER = {
    'cont_archive': 'Archive',
    'cont_compressor': 'Compressor',
    'cont_diskimage': 'Disk image',
    'cont_snapshot': 'Snapshot',
    'cont_decompiler': 'Player decompiler',
    'cont_multitrack': 'Multitrack file',
    'cont_scaner': 'Raw data scanner',
}


def esc(text):
    for a, b in (('\\', r'\textbackslash{}'), ('&', r'\&'), ('%', r'\%'), ('$', r'\$'), ('#', r'\#'),
                 ('_', r'\_'), ('{', r'\{'), ('}', r'\}'), ('~', r'\textasciitilde{}'), ('^', r'\textasciicircum{}')):
        text = text.replace(a, b)
    return text


# rips of consoles sound programs, played by emulation of their sound hardware
CONSOLES = {
    '2SF': 'Nintendo DS', 'NCSF': 'Nintendo DS', 'GSF': 'Game Boy Advance', 'PSF': 'PlayStation',
    'PSF2': 'PlayStation 2', 'SNSF': 'Super Nintendo', 'SSF': 'Sega Saturn', 'DSF': 'Dreamcast', 'USF': 'Nintendo 64',
}
AUDIO = {'AAC', 'AC3', 'AIFC', 'AIFF', 'APE', 'ASF', 'CAF', 'FLAC', 'M4A', 'MP3', 'MPC', 'OGG', 'OMA', 'OPUS', 'TAK',
         'WAV'}


def family(plugin, desc, caps):
    specific = [DEVICE[c] for c in caps if c in DEVICE and c != 'dev_dac']
    if specific:
        return ', '.join(specific)
    if plugin in CONSOLES:
        return 'Console: ' + CONSOLES[plugin]
    if plugin == 'MIDI':
        return 'MIDI (Roland MT-32)'
    if plugin in AUDIO and ('Audio' in desc or 'Vorbis' in desc or 'Opus' in desc or plugin in ('FLAC', 'APE', 'MPC', 'TAK', 'WAV', 'AC3')):
        return 'Standard audio'
    if 'mod_track' in caps:
        return 'Tracker (samples)'
    return 'Game audio stream'


def pick(caps, table, default='--'):
    # specific devices first, generic digital output last
    found = [table[c] for c in caps if c in table and c != 'dev_dac']
    if not found and 'dev_dac' in caps and table is DEVICE:
        found = [DEVICE['dev_dac']]
    return ', '.join(found) if found else default


EN = '--lang=en' in sys.argv
LABELS = {
    'family': 'Family' if EN else 'Famille',
    'container': 'Container' if EN else 'Conteneur',
}


def main():
    items = re.findall(r'Plugin:\s+(\S+)\nDescription:\s+(.*)\nCapabilities:\s+(.*)', sys.stdin.read())
    modules = [(p, d, c.split()) for p, d, c in items if 'cat_module' in c]
    containers = [(p, d, c.split()) for p, d, c in items if 'cat_container' in c]
    out = []
    out.append('% generated by tools/formats.py, do not edit\n')
    out.append(r'\newcommand{\lhunaModulesCount}{%d}' % len(modules))
    out.append(r'\newcommand{\lhunaContainersCount}{%d}' % len(containers))
    out.append(r'\newcommand{\lhunaFormatsTable}{%')
    out.append(r'\begin{longtable}{@{}l p{0.46\textwidth} l l@{}}')
    out.append(r'\toprule \textbf{Id} & \textbf{Format} & \textbf{Type} & \textbf{%s}' % LABELS['family'] + r' \\ \midrule \endhead')
    for p, d, caps in sorted(modules, key=lambda m: (family(*m), m[0])):
        out.append('%s & %s & %s & %s \\\\' % (esc(p), esc(d), pick(caps, KIND), esc(family(p, d, caps))))
    out.append(r'\bottomrule \end{longtable}}')
    out.append(r'\newcommand{\lhunaContainersTable}{%')
    out.append(r'\begin{longtable}{@{}l p{0.55\textwidth} l@{}}')
    out.append(r'\toprule \textbf{Id} & \textbf{%s} & \textbf{Type}' % LABELS['container'] + r' \\ \midrule \endhead')
    for p, d, caps in sorted(containers, key=lambda m: (pick(m[2], CONTAINER), m[0])):
        out.append('%s & %s & %s \\\\' % (esc(p), esc(d), pick(caps, CONTAINER)))
    out.append(r'\bottomrule \end{longtable}}')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
