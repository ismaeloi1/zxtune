#!/usr/bin/env python3
"""Generates reference of all settings of the Android app from its preferences XML and string resources.
Argument: path to app's res/ directory. French strings are used when available, English otherwise."""
import glob
import os
import re
import sys
import xml.etree.ElementTree as ET

EN = '--lang=en' in sys.argv
ANDROID = '{http://schemas.android.com/apk/res/android}'
APP = '{http://schemas.android.com/apk/res-auto}'


def load_values(folder):
    strings, arrays, ints = {}, {}, {}
    for path in glob.glob(os.path.join(folder, '*.xml')):
        try:
            root = ET.parse(path).getroot()
        except ET.ParseError:
            continue
        for e in root:
            name = e.get('name')
            if e.tag == 'string':
                strings[name] = ''.join(e.itertext())
            elif e.tag in ('string-array', 'array'):
                arrays[name] = [''.join(i.itertext()) for i in e]
            elif e.tag == 'integer':
                ints[name] = (e.text or '').strip()
    return strings, arrays, ints


def esc(text):
    text = text.replace('\\\'', '\'').replace('\\"', '"').replace('\\n', ' ')
    for a, b in (('\\', r'\textbackslash{}'), ('&', r'\&'), ('%', r'\%'), ('$', r'\$'), ('#', r'\#'), ('_', r'\_'),
                 ('{', r'\{'), ('}', r'\}'), ('~', r'\textasciitilde{}'), ('^', r'\textasciicircum{}')):
        text = text.replace(a, b)
    for a, b in (('×', r'$\times$'), ('→', r'$\rightarrow$'), ('←', r'$\leftarrow$'), ('≈', r'$\approx$')):
        text = text.replace(a, b)
    return text


class Resolver:
    def __init__(self, res, english):
        self.base = load_values(os.path.join(res, 'values'))
        # English is the base resources language
        self.fr = ({}, {}, {}) if english else load_values(os.path.join(res, 'values-fr'))

    def get(self, ref, kind=0):
        if not ref or not ref.startswith('@'):
            return ref
        name = ref.split('/', 1)[1]
        for source in (self.fr, self.base):
            if name in source[kind]:
                value = source[kind][name]
                return self.get(value, kind) if isinstance(value, str) and value.startswith('@') else value
        return None

    def text(self, ref):
        return self.get(ref, 0)

    def array(self, ref):
        items = self.get(ref, 1)
        return [self.text(i) or i for i in items] if items else items

    def default(self, ref):
        if ref is None:
            return None
        if ref.startswith('@integer/'):
            return self.get(ref, 2)
        if ref.startswith('@string/'):
            return self.text(ref) or ref
        return ref


def describe(elem, res):
    key = elem.get(ANDROID + 'key')
    title = res.text(elem.get(ANDROID + 'title')) or key
    summary = res.text(elem.get(ANDROID + 'summary')) or ''
    default = res.default(elem.get(ANDROID + 'defaultValue'))
    entries = res.array(elem.get(ANDROID + 'entries'))
    values = res.array(elem.get(ANDROID + 'entryValues'))
    kind = elem.tag.split('.')[-1]
    if entries and values and default is not None and default in values:
        default = entries[values.index(default)]
    if kind in ('SwitchPreferenceCompat', 'CheckBoxPreference', 'SwitchPreference') and default is not None:
        default = ('on' if EN else 'activé') if default == 'true' else ('off' if EN else 'désactivé')
    if kind == 'ValueSeekBarPreference':
        low = elem.get(APP + 'min') or '0'
        high = elem.get(ANDROID + 'max') or '?'
        fmt = res.text(elem.get(APP + 'valueFormat'))
        unit = (fmt or '%d').replace('%%', '%')
        rng = ('%s to %s' if EN else '%s à %s') % (unit.replace('%d', low).replace('%+d', low), unit.replace('%d', high).replace('%+d', high))
        summary = (summary + ' ' if summary else '') + ('(range: ' if EN else '(plage : ') + rng + ')'
        if default is not None and fmt:
            default = fmt.replace('%+d', default).replace('%d', default).replace('%%', '%')
    choices = ', '.join(entries) if entries else ''
    return key, title, summary, default, choices


def walk(elem, res, out, depth=0):
    for child in elem:
        tag = child.tag.split('.')[-1]
        if tag in ('PreferenceCategory', 'PreferenceScreen'):
            title = res.text(child.get(ANDROID + 'title'))
            if title:
                out.append((r'\subsection*{%s}' % esc(title), None))
            walk(child, res, out, depth + 1)
        elif child.get(ANDROID + 'key'):
            out.append((None, describe(child, res)))


def main():
    resdir = sys.argv[1]
    res = Resolver(resdir, EN)
    lines = ['% generated by tools/settings.py, do not edit']
    sections = (('preferences', 'Settings' if EN else 'Réglages'), ('preferences_oscilloscope', 'Oscilloscope'),
                ('preferences_mixer3', 'Mixer' if EN else 'Mixage'), ('preferences_car', 'Android Auto'))
    for name, label in sections:
        root = ET.parse(os.path.join(resdir, 'xml', name + '.xml')).getroot()
        items = []
        walk(root, res, items)
        lines.append(r'\section{%s}' % label)
        in_list = False
        for heading, item in items:
            if heading:
                if in_list:
                    lines.append(r'\end{description}')
                    in_list = False
                lines.append(heading)
                continue
            if not in_list:
                lines.append(r'\begin{description}')
                in_list = True
            key, title, summary, default, choices = item
            text = r'\item[%s] %s' % (esc(title), esc(summary))
            if choices:
                text += (r' \emph{Choices:} %s.' if EN else r' \emph{Choix :} %s.') % esc(choices)
            if default not in (None, ''):
                text += (r' \emph{Default:} %s.' if EN else r' \emph{Par défaut :} %s.') % esc(default)
            text += r' {\footnotesize\texttt{%s}}' % esc(key)
            lines.append(text)
        if in_list:
            lines.append(r'\end{description}')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
