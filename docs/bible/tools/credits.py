#!/usr/bin/env python3
"""Generates list of third party components and their licenses from 3rdparty/ directory (argument)."""
import os
import re
import sys

KNOWN = [
    ('GNU LESSER GENERAL PUBLIC LICENSE', 'Version 3', 'LGPL v3'),
    ('GNU LESSER GENERAL PUBLIC LICENSE', 'Version 2.1', 'LGPL v2.1'),
    ('GNU LIBRARY GENERAL PUBLIC LICENSE', 'Version 2', 'LGPL v2'),
    ('GNU GENERAL PUBLIC LICENSE', 'Version 3', 'GPL v3'),
    ('GNU GENERAL PUBLIC LICENSE', 'Version 2', 'GPL v2'),
    ('Mozilla Public License Version 2.0', '', 'MPL 2.0'),
    ('MIT License', '', 'MIT'),
    ('Permission is hereby granted, free of charge', '', 'MIT'),
    ('BSD 2-Clause', '', 'BSD 2-clause'),
    ('BSD 3-Clause', '', 'BSD 3-clause'),
    ('Redistribution and use in source and binary forms', '', 'BSD'),
    ('Permission to use, copy, modify, and/or distribute', '', 'ISC'),
    ('The Artistic License 2.0', '', 'Artistic 2.0'),
    ('CC0 1.0 Universal', '', 'CC0'),
    ('DO WHAT THE FUCK YOU WANT TO PUBLIC LICENSE', '', 'WTFPL'),
    ('UnRAR', '', 'UnRAR (freeware, source available)'),
]


# license files without standard header, checked by hand
OVERRIDES = {
    'curl': 'curl (MIT-like)',
    'vgmstream': 'ISC-like (see COPYING)',
    'mpg123': 'LGPL v2.1',
    'FLAC': 'BSD (Xiph)',
}


def license_of(path):
    # header only: license texts mention other licenses further
    text = open(path, errors='replace').read(400)
    flat = re.sub(r'\s+', ' ', text)
    for marker, version, name in KNOWN:
        if marker.lower() in flat.lower() and version.lower() in flat.lower():
            return name
    return 'see ' + os.path.basename(path)


def main():
    root = sys.argv[1]
    rows = []
    for name in sorted(os.listdir(root)):
        folder = os.path.join(root, name)
        if not os.path.isdir(folder):
            continue
        # nested components (e.g. snesspc/ares) have their own licenses
        for sub, _, names in sorted(os.walk(folder)):
            depth = os.path.relpath(sub, root).count(os.sep)
            files = [f for f in names if re.match(r'(?i)^(licen[cs]e|copying)(\.(md|txt|xiph))?$', f)]
            component = os.path.relpath(sub, root)
            if files and depth <= 1 and not component.endswith('/doc'):
                lic = OVERRIDES.get(component) or license_of(os.path.join(sub, sorted(files)[0]))
                rows.append((component, lic))
    print('% generated by tools/credits.py, do not edit')
    print(r'\begin{longtable}{@{}l l@{}}')
    print(r'\toprule \textbf{Composant (dossier)} & \textbf{Licence} \\ \midrule \endhead')
    for name, lic in rows:
        print(r'\texttt{%s} & %s \\' % (name.replace('_', r'\_'), lic))
    print(r'\bottomrule \end{longtable}')


if __name__ == '__main__':
    main()
